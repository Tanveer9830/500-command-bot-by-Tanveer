#!/usr/bin/env node
'use strict';
/**
 * Keeps the shell installer's branding in lock-step with src/utils/branding.js, and assembles install.sh:
 *   install.sh = deploy/install.head.sh + deploy/lib.sh (with generated BRAND region) + deploy/install.body.sh
 * `--check` exits 1 if the committed files are out of date (used by the test-suite).
 */
const fs = require('node:fs');
const path = require('node:path');
const b = require('../src/utils/branding');
const { IDENTITY } = require('../src/constants');

const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const q = (s) => `'${s.replace(/'/g, `'\\''`)}'`;
const lines = (arr) => arr.map((l) => `    printf '%s\\n' ${q(l)}`).join('\n');
const panel = (unicode) => b.renderPanel({ color: false, unicode, columns: 200 }).split('\n');

function brandRegion() {
  const logoU = b.LOGO_LINES; const logoA = b.LOGO_LINES.map(b.toAscii);
  return [
    '# >>> BRAND (generated by scripts/sync-installer.js from src/utils/branding.js; do not edit by hand)',
    `TP_LOGO_WIDTH=${b.LOGO_WIDTH}`, `TP_PANEL_WIDTH=${b.PANEL_WIDTH}`,
    `TP_ATTRIBUTION=${q(IDENTITY.ATTRIBUTION_UPPER)}`, `TP_SIGNATURE=${q(IDENTITY.SIGNATURE)}`,
    'tp_logo_lines() {', '  if [ "$TP_UNICODE" = 1 ]; then', lines(logoU), '  else', lines(logoA), '  fi', '}',
    'tp_panel_lines() {', '  if [ "$TP_UNICODE" = 1 ]; then', lines(panel(true)), '  else', lines(panel(false)), '  fi', '}',
    '# <<< BRAND',
  ].join('\n');
}

function assemble() {
  let lib = read('deploy/lib.sh');
  lib = lib.replace(/# >>> BRAND[\s\S]*?# <<< BRAND/, brandRegion());
  const install = `${read('deploy/install.head.sh')}\n# >>> SHARED LIB (deploy/lib.sh)\n${lib.replace(/^#!.*\n/, '')}\n# <<< SHARED LIB\n\n${read('deploy/install.body.sh')}`;
  return { lib, install };
}

const { lib, install } = assemble();
if (process.argv.includes('--check')) {
  const stale = [];
  if (read('deploy/lib.sh') !== lib) stale.push('deploy/lib.sh');
  if (read('install.sh') !== install) stale.push('install.sh');
  if (stale.length) { console.error(`out of date: ${stale.join(', ')} — run: node scripts/sync-installer.js`); process.exit(1); }
  console.log('installer is in sync with branding');
} else {
  fs.writeFileSync(path.join(root, 'deploy/lib.sh'), lib);
  fs.writeFileSync(path.join(root, 'install.sh'), install, { mode: 0o755 });
  console.log('wrote deploy/lib.sh and install.sh');
}
