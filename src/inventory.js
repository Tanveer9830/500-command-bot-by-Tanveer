'use strict';
/** Command inventory + counts, generated from the live registry (never hand-written). */
const fs = require('node:fs');
const path = require('node:path');

const FORBIDDEN = /^(pin|unpin|tag|notag|untag|mention|ghostping|poke|nudge|summon|wake|buzz)$/i;

function behavioralKeys(testDir) {
  const keys = new Set();
  for (const f of fs.readdirSync(testDir)) {
    if (!f.endsWith('.test.js') || f === 'smoke.test.js') continue;
    const src = fs.readFileSync(path.join(testDir, f), 'utf8');
    for (const m of src.matchAll(/['"`]([a-z0-9]+(?:\.[a-z0-9]+){1,2})['"`]/g)) keys.add(m[1]);
  }
  return keys;
}

function counts(registry) {
  const all = registry.all(); const slash = registry.toSlashJSON();
  const by = (t) => all.filter((a) => a.access === t).length;
  const subs = slash.reduce((n, c) => n + (c.options ? c.options.filter((o) => o.type === 1 || o.type === 2).reduce((m, o) => m + (o.type === 2 ? (o.options || []).length : 1), 0) : 0), 0);
  return {
    totalActions: all.length, normalUser: by('user'), adminOnly: by('admin'), ownerOnly: by('owner'), adminTier: by('admin') + by('owner'),
    slashTopLevel: slash.length, slashSubcommands: subs, groups: registry.groups.size, standaloneSlash: registry.standaloneActions.size,
    explicitAliases: all.reduce((n, a) => n + a.aliases.length, 0) + [...registry.groups.values()].reduce((n, g) => n + g.aliases.length, 0),
    categories: new Set(all.map((a) => a.category)).size,
  };
}

function buildInventory(registry, { testDir = path.join(__dirname, '..', 'tests') } = {}) {
  const behavioral = behavioralKeys(testDir);
  const flatReverse = new Map();
  for (const [name, a] of registry.flat) { if (!flatReverse.has(a)) flatReverse.set(a, []); flatReverse.get(a).push(name); }
  const standaloneBy = new Map();
  for (const [name, a] of registry.standaloneActions) { if (!standaloneBy.has(a)) standaloneBy.set(a, []); standaloneBy.get(a).push(name); }
  return registry.all().map((a) => {
    const g = a.group; const path_ = [g.name, a.subgroup, a.sub].filter(Boolean).join(' ');
    const flat = (flatReverse.get(a) || []).filter((n) => n !== a.sub || true);
    const stand = standaloneBy.get(a) || [];
    return {
      key: a.key, name: path_, aliases: [...a.aliases, ...g.aliases.map((x) => `${x} ${[a.subgroup, a.sub].filter(Boolean).join(' ')}`)],
      category: a.category, tier: a.access === 'user' ? 'normal' : a.access, access: a.access,
      slash: `/${path_}`, prefix: `!${path_}`, shortPrefix: flat.map((n) => `!${n}`),
      perms: a.perms, botPerms: a.botPerms, guildOnly: a.guildOnly, cooldown: a.cooldown,
      status: 'implemented', slashStatus: stand.length ? `registered (/${path_.split(' ')[0]} group + standalone ${stand.map((s) => `/${s}`).join(', ')})` : `registered (/${g.name} group)`,
      testStatus: behavioral.has(a.key) ? 'smoke + behavioral' : 'smoke',
      description: a.description,
    };
  });
}

function toMarkdown(rows, c, { generatedAt = new Date().toISOString() } = {}) {
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const beh = rows.filter((r) => r.testStatus !== 'smoke').length;
  const lines = [
    '# TANVEER PRIME — command inventory', '',
    '> Generated by `npm run inventory` from the live command registry. Do not edit by hand.',
    '> MADE BY TANVEER | DISCORD: TANVEER5637', '',
    '## Counts', '',
    `| Metric | Count |`, `|---|---|`,
    `| Distinct registered actions | **${c.totalActions}** |`,
    `| Normal-user actions | **${c.normalUser}** |`,
    `| Admin-tier actions (admin + owner) | **${c.adminTier}** (${c.adminOnly} admin, ${c.ownerOnly} Global-Owner-only) |`,
    `| Top-level slash commands registered with Discord | **${c.slashTopLevel}** (limit 100) — ${c.groups} groups + ${c.standaloneSlash} standalone shortcuts |`,
    `| Slash subcommands inside those groups | ${c.slashSubcommands} |`,
    `| Explicit aliases (NOT counted as actions) | ${c.explicitAliases} |`,
    `| Actions with a dedicated behavioral test | ${beh} of ${c.totalActions} |`,
    `| Actions covered by the generic smoke test | ${c.totalActions} of ${c.totalActions} |`, '',
    '**How to read this.** An *action* is one registry entry with its own handler. Aliases, the short `!name` forms and the standalone slash shortcuts are extra *routes* to an existing action and are never counted twice. Every action is reachable as `/group sub` and as `!group sub` through the same registry and the same authorization pipeline.', '',
    '**Test status.** `smoke` = the action is executed against mocked Discord objects by the generic smoke test and checked for a well-formed result and correct admin/user authorization. `smoke + behavioral` = additionally named in a dedicated test file that asserts specific outcomes. **Nothing here has been run against a live Discord server by this generator.**', '',
    '## Actions', '',
    '| Canonical name | Aliases | Category | Tier | Slash | Prefix | Permissions | Status | Slash status | Test status |', '|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    lines.push(`| \`${esc(r.name)}\` | ${r.aliases.length ? esc(r.aliases.map((a) => `\`${a}\``).join(', ')) : '—'} | ${esc(r.category)} | ${r.tier} | \`${esc(r.slash)}\` | \`${esc(r.prefix)}\`${r.shortPrefix.length ? ` (also ${r.shortPrefix.slice(0, 3).map((s) => `\`${s}\``).join(', ')})` : ''} | ${r.perms.length ? r.perms.join(', ') : '—'} | ${r.status} | ${esc(r.slashStatus)} | ${r.testStatus} |`);
  }
  lines.push('', `_Generated ${generatedAt}._`, '');
  return lines.join('\n');
}

/** Hard checks used by `npm run validate` and the tests. Returns a list of problems. */
function validate(registry) {
  const problems = []; const c = counts(registry);
  if (c.slashTopLevel !== 100) problems.push(`expected exactly 100 top-level slash commands, found ${c.slashTopLevel}`);
  if (c.totalActions < 500) problems.push(`fewer than 500 actions (${c.totalActions})`);
  if (c.adminTier < 150) problems.push(`fewer than 150 admin-tier actions (${c.adminTier})`);
  if (c.normalUser < 350) problems.push(`fewer than 350 normal-user actions (${c.normalUser})`);
  for (const a of registry.all()) {
    const names = [a.group.name, a.subgroup, a.sub, ...a.aliases, ...a.group.aliases].filter(Boolean);
    if (names.some((n) => FORBIDDEN.test(n))) problems.push(`forbidden tag/pin-style name in ${a.key}`);
    if (!a.description || a.description.length > 100) problems.push(`${a.key}: description missing or >100 chars`);
  }
  for (const n of [...registry.standaloneActions.keys(), ...registry.groups.keys()]) if (FORBIDDEN.test(n)) problems.push(`forbidden top-level name ${n}`);
  return problems;
}

module.exports = { buildInventory, toMarkdown, counts, validate, FORBIDDEN };
